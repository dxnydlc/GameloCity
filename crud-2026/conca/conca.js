// CERRAR TAB
// ======================================================
function cerrarTab(event, tabId, contentId) {
  event.stopPropagation();

  const tabButton = document.getElementById(tabId);
  const tabLi = document.getElementById("li-" + tabId);
  const tabContent = document.getElementById(contentId);

  const isActive = tabButton.classList.contains("active");

  // Eliminar tab dinámico
  tabLi.remove();
  tabContent.remove();

  // Si el tab cerrado era el activo → activar tab de Listado
  if (isActive) {
    const listadoTab = document.getElementById("tab-listado");
    if (listadoTab) {
      new bootstrap.Tab(listadoTab).show();
    }
  }
}
