function handleFail(xhr, status, error) {
    const httpStatus = xhr.status;

    const handlers = {
        0:   () => toastr["error"]( 'No hay conexión con el servidor' , 'error' ) , 
        400: () => toastr["error"]( xhr.responseJSON?.message || 'Revise los datos enviados' , 'error' ) , 
        401: () => toastr["error"]( 'Su sesión ha expirado o no tiene permisos' , 'error' ) , 
        403: () => toastr["error"]( 'No tiene permisos para realizar esta acción' , 'error' ) , 
        404: () => toastr["error"]( 'El recurso solicitado no existe' , 'error' ) , 
        409: () => toastr["error"]( xhr.responseJSON?.message || 'El registro ya existe o está en uso' , 'error' ) , 
        422: () => mostrarErroresValidacion(xhr) , 
        500: () => toastr["error"]( 'Ocurrió un problema en el servidor' , 'error' ) , 
        503: () => toastr["error"]( 'El servidor está en mantenimiento' , 'error' ) , 
    };

    // Ejecuta el handler si existe, si no, usa uno genérico
    (handlers[httpStatus] || (() => {
        toastr["error"]( `Error inesperado (${httpStatus})` , 'error' );
    }))();
}
